import type { FaviconTheme } from "./settings";

/**
 * Generates a Tampermonkey / Violentmonkey userscript that repaints the favicons of
 * every page you visit so they follow the launcher's Material palette.
 *
 * The approach is the one you described: find `<link rel="icon">` in `<head>` and swap its
 * `href` for a canvas render of the wanted colour; when the page has no icon at all, create one.
 *
 * The script has no dependencies and asks for no privileges, so it can be installed as-is.
 * Nothing is sent anywhere: the icon is redrawn locally in a canvas.
 */

const SCRIPT_NAME = "LisYan — Material favicons";

/** Builds the full .user.js source for the given palette. */
export function buildFaviconUserscript(theme: FaviconTheme): string {
  const config = JSON.stringify({ mode: theme.mode, tint: theme.color }, null, 2);

  return [
    "// ==UserScript==",
    `// @name         ${SCRIPT_NAME}`,
    `// @namespace    lisyan.app`,
    `// @version      1.0.0`,
    `// @description  Repaints site favicons with the LisYan Material palette (${theme.mode}).`,
    `// @author       LisYan`,
    `// @match        *://*/*`,
    `// @run-at       document-end`,
    `// @grant        none`,
    `// @noframes     false`,
    `// ==/UserScript==`,
    "",
    "(function () {",
    '  "use strict";',
    "",
    "  var CONFIG = " + config + ";",
    "  // Inside the extension the live theme wins over the packaged default.",
    "  if (typeof chrome !== \"undefined\" && chrome.storage && chrome.storage.local) {",
    "    chrome.storage.local.get(\"lisyan_favicon_theme\", function (data) {",
    "      if (data && data.lisyan_favicon_theme && data.lisyan_favicon_theme.mode) {",
    "        CONFIG.mode = data.lisyan_favicon_theme.mode;",
    "        if (data.lisyan_favicon_theme.color) CONFIG.tint = data.lisyan_favicon_theme.color;",
    "        run();",
    "      }",
    "    });",
    "  }",
    '  var REL_SELECTOR = \'link[rel~="icon"], link[rel~="shortcut icon"], link[rel~="apple-touch-icon"], link[rel~="apple-touch-icon-precomposed"], link[rel~="mask-icon"]\';',
    "  var busy = new WeakSet();",
    "  var painted = new WeakMap();",
    "  var pending = 0;",
    "",
    "  function hexToRgb(hex) {",
    "    var clean = (hex || \"#f5f5f7\").replace(\"#\", \"\");",
    "    if (clean.length === 3) clean = clean[0] + clean[0] + clean[1] + clean[1] + clean[2] + clean[2];",
    "    return {",
    "      r: parseInt(clean.slice(0, 2), 16) || 0,",
    "      g: parseInt(clean.slice(2, 4), 16) || 0,",
    "      b: parseInt(clean.slice(4, 6), 16) || 0,",
    "    };",
    "  }",
    "",
    "  function paint(source, width, height) {",
    "    var size = Math.max(16, Math.min(128, Math.max(width || 32, height || 32)));",
    "    var canvas = document.createElement(\"canvas\");",
    "    canvas.width = size;",
    "    canvas.height = size;",
    "    var ctx = canvas.getContext(\"2d\", { willReadFrequently: true });",
    "    if (!ctx) return null;",
    "    ctx.imageSmoothingQuality = \"high\";",
    "    var scale = Math.min(size / (source.width || size), size / (source.height || size));",
    "    var w = (source.width || size) * scale;",
    "    var h = (source.height || size) * scale;",
    "    ctx.drawImage(source, (size - w) / 2, (size - h) / 2, w, h);",
    "",
    "    if (CONFIG.mode === \"original\") return canvas.toDataURL(\"image/png\");",
    "",
    "    var tint = hexToRgb(CONFIG.tint);",
    "    var image;",
    "    try {",
    "      image = ctx.getImageData(0, 0, size, size);",
    "    } catch (error) {",
    "      // Cross-origin favicon: the canvas is tainted, so fall back to a generated mark.",
    "      return null;",
    "    }",
    "    var data = image.data;",
    "    for (var i = 0; i < data.length; i += 4) {",
    "      var alpha = data[i + 3];",
    "      if (alpha === 0) continue;",
    "      if (CONFIG.mode === \"mono\") {",
    "        // Silhouette: keep the shape's alpha, replace every colour with the tint.",
    "        data[i] = tint.r;",
    "        data[i + 1] = tint.g;",
    "        data[i + 2] = tint.b;",
    "      } else {",
    "        // Themed: keep the logo's internal shading, repaint its hue with the tint.",
    "        var luma = (data[i] * 0.2126 + data[i + 1] * 0.7152 + data[i + 2] * 0.0722) / 255;",
    "        var k = 0.55 + 0.9 * luma;",
    "        data[i] = Math.max(0, Math.min(255, tint.r * k));",
    "        data[i + 1] = Math.max(0, Math.min(255, tint.g * k));",
    "        data[i + 2] = Math.max(0, Math.min(255, tint.b * k));",
    "      }",
    "    }",
    "    ctx.putImageData(image, 0, 0);",
    "    // An empty or invisible source must not produce a blank icon — fall back to the monogram.",
    "    var out = ctx.getImageData(0, 0, size, size).data;",
    "    var coverage = 0;",
    "    for (var j = 3; j < out.length; j += 4) { if (out[j] > 120) coverage += 1; }",
    "    if (coverage < size) return null;",
    "    return canvas.toDataURL(\"image/png\");",
    "  }",
    "",
    "  // A generated mark: the site's initial on a tinted square. Used when there is no icon to read.",
    "  function monogram() {",
    "    var size = 64;",
    "    var canvas = document.createElement(\"canvas\");",
    "    canvas.width = canvas.height = size;",
    "    var ctx = canvas.getContext(\"2d\", { willReadFrequently: true });",
    "    if (!ctx) return null;",
    "    var tint = hexToRgb(CONFIG.tint);",
    "    var background = CONFIG.mode === \"mono\" ? tint : { r: tint.r * 0.45, g: tint.g * 0.45, b: tint.b * 0.45 };",
    "    ctx.fillStyle = \"rgb(\" + background.r + \",\" + background.g + \",\" + background.b + \")\";",
    "    ctx.beginPath();",
    "    if (ctx.roundRect) ctx.roundRect(0, 0, size, size, size * 0.32);",
    "    else ctx.rect(0, 0, size, size);",
    "    ctx.fill();",
    "    var letter = (location.hostname.replace(/^www\\\\./, \"\")[0] || \"L\").toUpperCase();",
    "    ctx.fillStyle = \"rgb(\" + tint.r + \",\" + tint.g + \",\" + tint.b + \")\";",
    "    ctx.font = \"700 \" + Math.round(size * 0.58) + \"px system-ui, sans-serif\";",
    "    ctx.textAlign = \"center\";",
    "    ctx.textBaseline = \"middle\";",
    "    ctx.fillText(letter, size / 2, size / 2 + size * 0.02);",
    "    return canvas.toDataURL(\"image/png\");",
    "  }",
    "",
    "  function apply(link) {",
    "    if (!link || busy.has(link)) return;",
    "    var href = link.getAttribute(\"href\");",
    "    if (!href) return;",
    "    // Nothing to do on our own previous output, and on data: URLs only when they are not ours.",
    "    if (painted.get(link) === href) return;",
    "    if (CONFIG.mode === \"original\") return;",
    "    busy.add(link);",
    "",
    "    var absolute;",
    "    try {",
    "      absolute = new URL(href, location.href).href;",
    "    } catch (error) {",
    "      return;",
    "    }",
    "",
    "    var image = new Image();",
    "    image.crossOrigin = \"anonymous\";",
    "    var finish = function (result) {",
    "      busy.delete(link);",
    "      if (!result) return;",
    "      painted.set(link, result);",
    "      link.setAttribute(\"href\", result);",
    "    };",
    "    image.onload = function () {",
    "      finish(paint(image, image.naturalWidth, image.naturalHeight) || monogram());",
    "    };",
    "    image.onerror = function () {",
    "      finish(monogram());",
    "    };",
    "    image.src = absolute;",
    "  }",
    "",
    "  function run() {",
    "    var links = document.head ? document.head.querySelectorAll(REL_SELECTOR) : [];",
    "    for (var i = 0; i < links.length; i += 1) apply(links[i]);",
    "    if (!links.length) {",
    "      // The page ships no favicon at all: add one so the tab is themed too.",
    "      var link = document.createElement(\"link\");",
    "      link.setAttribute(\"rel\", \"icon\");",
    "      link.setAttribute(\"type\", \"image/png\");",
    "      link.setAttribute(\"href\", monogram() || \"\");",
    "      (document.head || document.documentElement).appendChild(link);",
    "    }",
    "  }",
    "",
    "  function schedule() {",
    "    if (pending) return;",
    "    pending = window.setTimeout(function () {",
    "      pending = 0;",
    "      run();",
    "    }, 250);",
    "  }",
    "",
    "  if (document.readyState === \"loading\") document.addEventListener(\"DOMContentLoaded\", run, { once: true });",
    "  else run();",
    "",
    "  // SPAs (Gmail, YouTube…) swap the favicon for unread badges — keep up with them.",
    "  if (document.head && typeof MutationObserver !== \"undefined\") {",
    "    new MutationObserver(schedule).observe(document.head, { childList: true, subtree: true, attributes: true, attributeFilter: [\"href\", \"rel\"] });",
    "  }",
    "",
    "  // The extension's background worker sends this when the theme changes or on startup,",
    "  // so tabs that are ALREADY OPEN get repainted too — no reload needed.",
    "  if (typeof chrome !== \"undefined\" && chrome.runtime && chrome.runtime.onMessage) {",
    "    chrome.runtime.onMessage.addListener(function (message) {",
    "      if (message && message.type === \"lisyan:repaint-favicon\") {",
    "        done = new WeakSet();",
    "        painted = new WeakMap();",
    "        run();",
    "      }",
    "    });",
    "  }",
    "})();",
    "",
  ].join("\n");
}

export const faviconUserscriptName = () => "lisyan-favicon-theme.user.js";
