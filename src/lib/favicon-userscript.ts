import type { FaviconTheme } from "./settings";
import { recolorFavicon, themeFaviconImage } from "./favicon-recolor";

/**
 * Generates the content script (also usable as a Tampermonkey / Violentmonkey userscript) that
 * repaints the favicon of every page with the launcher's Material palette — the same multi-tone
 * system as the app-menu icons (see favicon-recolor.ts, whose functions are embedded verbatim).
 *
 * Favicons on other origins cannot be read by the page (CORS). Inside the extension the script then
 * asks the background worker, which may fetch any http(s) URL, for the image as a data: URL.
 * Nothing leaves the browser: icons are fetched from their own sites and redrawn locally.
 */

const SCRIPT_NAME = "LisYan — Material favicons";

/** Builds the full .user.js source for the given palette. */
export function buildFaviconUserscript(theme: FaviconTheme): string {
  const config = JSON.stringify({ mode: theme.mode, tint: theme.color, palette: theme.palette ?? null }, null, 2);

  return [
    "// ==UserScript==",
    `// @name         ${SCRIPT_NAME}`,
    `// @namespace    lisyan.app`,
    `// @version      2.0.0`,
    `// @description  Repaints site favicons with the LisYan Material palette (${theme.mode}).`,
    `// @author       LisYan`,
    `// @match        *://*/*`,
    `// @run-at       document-end`,
    `// @grant        none`,
    `// @noframes     false`,
    `// ==/UserScript==`,
    "",
    "(function () {",
    '  "use strict";',
    "",
    "  // Injected again into an already-themed frame: the repaint message that follows does the work.",
    "  if (window.__lisyanFavicons) return;",
    "  window.__lisyanFavicons = true;",
    "  var CONFIG = " + config + ";",
    "  // The recolour pipeline — identical to the launcher's preview (src/lib/favicon-recolor.ts).",
    "  var recolorFavicon = (" + recolorFavicon.toString() + ");",
    "  var themeFaviconImage = (" + themeFaviconImage.toString() + ");",
    "",
    "  function takeTheme(next) {",
    "    if (!next) return false;",
    "    if (next.mode) CONFIG.mode = next.mode;",
    "    if (next.color) CONFIG.tint = next.color;",
    "    if (next.palette) CONFIG.palette = next.palette;",
    "    return true;",
    "  }",
    "  var hasChrome = typeof chrome !== \"undefined\" && chrome.runtime && chrome.runtime.id;",
    "  if (hasChrome && chrome.storage && chrome.storage.local) {",
    "    chrome.storage.local.get(\"lisyan_favicon_theme\", function (data) {",
    "      if (data && data.lisyan_favicon_theme) takeTheme(data.lisyan_favicon_theme);",
    "      repaintAll();",
    "    });",
    "    // Palette edits in the launcher repaint every open tab without a reload.",
    "    if (chrome.storage.onChanged) chrome.storage.onChanged.addListener(function (changes, area) {",
    "      if (area !== \"local\" || !changes.lisyan_favicon_theme) return;",
    "      if (takeTheme(changes.lisyan_favicon_theme.newValue)) repaintAll();",
    "    });",
    "  }",
    '  var REL_SELECTOR = \'link[rel~="icon"], link[rel~="shortcut"], link[rel~="apple-touch-icon"], link[rel~="apple-touch-icon-precomposed"], link[rel~="mask-icon"]\';',
    "  var busy = new WeakSet();",
    "  var painted = new WeakMap();",
    "  var originals = new WeakMap();",
    "  var reported = new WeakMap();",
    "  var pending = 0;",
    "",
    "  function palette() {",
    "    var p = CONFIG.palette || {};",
    "    if (!p.ink) p.ink = CONFIG.tint || \"#6750a4\";",
    "    return p;",
    "  }",
    "",
    "  // A generated mark (the site's initial) for pages whose icon cannot be read at all.",
    "  function monogram() {",
    "    var size = 64, p = palette();",
    "    var canvas = document.createElement(\"canvas\");",
    "    canvas.width = canvas.height = size;",
    "    var ctx = canvas.getContext(\"2d\");",
    "    if (!ctx) return null;",
    "    var themed = CONFIG.mode !== \"mono\";",
    "    if (themed) {",
    "      ctx.fillStyle = p.tile || \"#e8def8\";",
    "      ctx.beginPath();",
    "      if (ctx.roundRect) ctx.roundRect(0, 0, size, size, size * 0.3); else ctx.rect(0, 0, size, size);",
    "      ctx.fill();",
    "    }",
    "    var letter = (location.hostname.replace(/^www\\./, \"\")[0] || \"L\").toUpperCase();",
    "    ctx.fillStyle = p.ink;",
    "    ctx.font = \"700 \" + Math.round(size * (themed ? 0.5 : 0.7)) + \"px system-ui, sans-serif\";",
    "    ctx.textAlign = \"center\";",
    "    ctx.textBaseline = \"middle\";",
    "    ctx.fillText(letter, size / 2, size / 2 + size * 0.03);",
    "    return canvas.toDataURL(\"image/png\");",
    "  }",
    "",
    "  // Cross-origin icon: ask the extension's background worker for it as a data: URL.",
    "  function viaExtension(url, done) {",
    "    if (!hasChrome || !chrome.runtime.sendMessage) { done(null); return; }",
    "    try {",
    "      chrome.runtime.sendMessage({ type: \"lisyan:fetch-icon\", url: url }, function (response) {",
    "        if (chrome.runtime.lastError) { done(null); return; }",
    "        done(response && response.dataUrl ? response.dataUrl : null);",
    "      });",
    "    } catch (error) { done(null); }",
    "  }",
    "",
    "  function load(src, cors, done) {",
    "    var image = new Image();",
    "    if (cors) image.crossOrigin = \"anonymous\";",
    "    image.onload = function () { done(themeFaviconImage(image, palette(), CONFIG.mode, recolorFavicon)); };",
    "    image.onerror = function () { done(null); };",
    "    image.src = src;",
    "  }",
    "",
    "  // Capture a site's original favicon on each visit; the background stores it by host and refreshes lastSeenAt.",
    "  function cacheSiteIcon(link) {",
    "    if (typeof chrome === \"undefined\" || !chrome.runtime || !chrome.runtime.id || !chrome.runtime.sendMessage) return;",
    "    var raw = link && (link.getAttribute(\"href\") || originals.get(link));",
    "    if (!raw || /^data:/i.test(raw)) raw = link && originals.get(link);",
    "    if (!raw || /^data:/i.test(raw)) return;",
    "    var absolute;",
    "    try { absolute = new URL(raw, location.href).href; } catch (error) { return; }",
    "    if (!/^https?:/i.test(absolute) || reported.get(link) === absolute) return;",
    "    reported.set(link, absolute);",
    "    try { chrome.runtime.sendMessage({ type: \"lisyan:cache-site-icon\", pageUrl: location.href, iconUrl: absolute }, function () { void chrome.runtime.lastError; }); } catch (error) {}",
    "  }",
    "",
    "  function apply(link) {",
    "    if (!link || busy.has(link)) return;",
    "    var href = link.getAttribute(\"href\");",
    "    if (!href) return;",
    "    if (painted.get(link) === href) return;",
    "    if (CONFIG.mode === \"original\") {",
    "      if (originals.has(link) && painted.has(link)) { link.setAttribute(\"href\", originals.get(link)); painted.delete(link); }",
    "      return;",
    "    }",
    "    if (!originals.has(link)) originals.set(link, href);",
    "    var absolute;",
    "    try { absolute = new URL(originals.get(link) || href, location.href).href; } catch (error) { return; }",
    "    busy.add(link);",
    "    var finish = function (result) {",
    "      busy.delete(link);",
    "      result = result || monogram();",
    "      if (!result) return;",
    "      painted.set(link, result);",
    "      link.setAttribute(\"href\", result);",
    "      if (link.hasAttribute(\"color\")) link.removeAttribute(\"color\");",
    "    };",
    "    var sameOrigin = absolute.indexOf(location.origin + \"/\") === 0 || /^data:/i.test(absolute);",
    "    // 1) read it directly (same origin, or a server that allows CORS), 2) through the extension.",
    "    load(absolute, !sameOrigin, function (result) {",
    "      if (result) { finish(result); return; }",
    "      viaExtension(absolute, function (dataUrl) {",
    "        if (!dataUrl) { finish(null); return; }",
    "        load(dataUrl, false, finish);",
    "      });",
    "    });",
    "  }",
    "",
    "  function run() {",
    "    var links = document.head ? document.head.querySelectorAll(REL_SELECTOR) : [];",
    "    for (var i = 0; i < links.length; i += 1) { cacheSiteIcon(links[i]); apply(links[i]); }",
    "    if (!links.length && CONFIG.mode !== \"original\") {",
    "      // No <link rel=icon>: the browser would use /favicon.ico — theme that one.",
    "      var link = document.createElement(\"link\");",
    "      link.setAttribute(\"rel\", \"icon\");",
    "      link.setAttribute(\"href\", \"/favicon.ico\");",
    "      (document.head || document.documentElement).appendChild(link);",
    "      apply(link);",
    "    }",
    "  }",
    "",
    "  function repaintAll() {",
    "    busy = new WeakSet();",
    "    painted = new WeakMap();",
    "    run();",
    "  }",
    "",
    "  function schedule() {",
    "    if (pending) return;",
    "    pending = window.setTimeout(function () {",
    "      pending = 0;",
    "      run();",
    "    }, 250);",
    "  }",
    "",
    "  if (!hasChrome) {",
    "    if (document.readyState === \"loading\") document.addEventListener(\"DOMContentLoaded\", run, { once: true });",
    "    else run();",
    "  }",
    "",
    "  // SPAs (Gmail, YouTube…) swap the favicon for unread badges — keep up with them.",
    "  if (document.head && typeof MutationObserver !== \"undefined\") {",
    "    new MutationObserver(schedule).observe(document.head, { childList: true, subtree: true, attributes: true, attributeFilter: [\"href\", \"rel\"] });",
    "  }",
    "",
    "  // The background worker sends this when the theme changes or on startup, so tabs that are",
    "  // ALREADY OPEN get repainted too — no reload needed.",
    "  if (hasChrome && chrome.runtime.onMessage) {",
    "    chrome.runtime.onMessage.addListener(function (message) {",
    "      if (message && (message.type === \"lisyan:repaint-favicon\" || message.type === \"lisyan:apply-favicon-theme\")) {",
    "        if (message.lisyanTheme) takeTheme(message.lisyanTheme);",
    "        repaintAll();",
    "      }",
    "    });",
    "  }",
    "})();",
    "",
  ].join("\n");
}

export const faviconUserscriptName = () => "lisyan-favicon-theme.user.js";
